a = int(input('введите число a:'))
b = int(input('введите число b:'))
summa = a ** 2 + b ** 2
rasn = a ** 2 - b ** 2
proiz = a ** 2 * b ** 2
chast = a ** 2 / b ** 2
print(f'Сумма равна: {summa}')
print(f'Разность равна: {rasn}')
print(f'Произведение равно: {proiz}')
print(f'Частное равно: {chast}')